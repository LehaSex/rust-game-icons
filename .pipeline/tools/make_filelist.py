
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HEADER = f"# generated by make_filelist.py, {Path(__file__).resolve().name}"
BUNDLE_RE = re.compile(r"^Bundles\\shared\\.*\.bundle$")
ITEMS_RE = re.compile(r"^Bundles\\items\\.*\.(png|json)$", re.IGNORECASE)


def parse_manifest(path: Path) -> dict[str, int]:
    out: dict[str, int] = {}
    with path.open(encoding="utf-8", errors="replace") as fh:
        header_done = False
        for line in fh:
            if not header_done:
                if line.startswith("Size") or ("Chunks" in line and "SHA" in line):
                    header_done = True
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            try:
                size = int(parts[0])
            except ValueError:
                continue
            out[parts[-1]] = size
    return out


def wanted(*names: str) -> int:
    lines = [HEADER,
             r"regex:^Bundles\\shared\\(content|items\.preload|skinnables\.preload)\.bundle$",
             r"regex:^Bundles\\items\\.*\.(png|json)$"]
    lines += [n for n in names if n and not n.startswith("#")]
    for line in lines:
        print(line)
    return 0


def icons(names_file: Path) -> int:
    print(HEADER)
    print(r"regex:^Bundles\\items\\.*\.(png|json)$")
    print("# explicit per shortname:")
    for raw in names_file.read_text(encoding="utf-8").splitlines():
        n = raw.strip()
        if n and not n.startswith("#"):
            print(f"Bundles\\items\\{n}.png")
            print(f"Bundles\\items\\{n}.json")
    return 0


def diff(before: Path, after: Path) -> int:
    a = parse_manifest(before)
    b = parse_manifest(after)
    added = sorted(set(b) - set(a))
    removed = sorted(set(a) - set(b))
    changed = sorted(p for p in (set(a) & set(b)) if a[p] != b[p])
    print(HEADER)
    print(f"# added {len(added)}, changed {len(changed)}, removed {len(removed)}")
    for p in added:
        print(p)
    for p in changed:
        print(p)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="wanted.txt generator for -filelist")
    sub = ap.add_subparsers(dest="cmd", required=True)

    w = sub.add_parser("wanted", help="bundles + all item icons")
    w.add_argument("extra", nargs="*", help="additional exact paths")
    w.add_argument("--out", type=Path, default=None)

    i = sub.add_parser("icons", help="only icons from a shortname list")
    i.add_argument("--names", type=Path, required=True)
    i.add_argument("--out", type=Path, default=None)

    d = sub.add_parser("diff", help="difference between two manifests")
    d.add_argument("--before", type=Path, required=True)
    d.add_argument("--after", type=Path, required=True)
    d.add_argument("--out", type=Path, default=None)

    args = ap.parse_args()
    if args.out:
                                                                        
        args.out.parent.mkdir(parents=True, exist_ok=True)
        with args.out.open("w", encoding="utf-8") as fh:
            old = sys.stdout
            sys.stdout = fh
            try:
                rc = _run(args)
            finally:
                sys.stdout = old
        print(args.out.read_text(encoding="utf-8"))
    else:
        rc = _run(args)
    return rc


def _run(args) -> int:
    if args.cmd == "wanted":
        return wanted(*args.extra)
    if args.cmd == "icons":
        return icons(args.names)
    return diff(args.before, args.after)


if __name__ == "__main__":
    sys.exit(main())